import time  # Подключаем модуль для замера точного времени выполнения кода
from functools import wraps  # Подключаем wraps для сохранения имени и описания исходной функции
from typing import Callable, Any  # Подключаем типы Callable (функция) и Any (произвольные данные)

def log_call(func: Callable[..., Any]) -> Callable[..., Any]:  # Декоратор №1: логирует вызовы методов нашей библиотеки
    """Декоратор №1: Журналирование вызова, параметров и результата."""

    @wraps(func)  # Сохраняем метаданные оригинальной функции, чтобы не ломать интроспекцию
    def wrapper(*args: Any, **kwargs: Any) -> Any:  # Функция-обертка, собирает любые входящие аргументы метода
        print(f"[LOG] Вызван метод: '{func.__name__}' с args={args[1:]} kwargs={kwargs}")  # Пишем имя метода и параметры
        try:  # Пробуем запустить оригинальный метод внутри защищенного блока
            result = func(*args, **kwargs)  # Распаковываем аргументы и запускаем реальный метод фонда
            print(f"[LOG] Метод '{func.__name__}' успешно завершился. Результат: {result}")  # Пишем лог успеха
            return result  # Возвращаем полученный результат дальше по цепочке в программу
        except Exception as e:  # Если внутри метода произошел сбой — ловим это исключение
            print(f"[LOG] В методе '{func.__name__}' произошло исключение: {type(e).__name__}: {e}")  # Логируем аварию
            raise  # Пробрасываем ошибку дальше в main.py для правильной обработки
    return wrapper  # Возвращаем готовую функцию-обертку обратно в систему

def measure_time(func: Callable[..., Any]) -> Callable[..., Any]:  # Декоратор №2: измеряет чистую скорость работы методов фонда
    """Декоратор №2: Измерение времени выполнения метода."""

    @wraps(func)  # Запоминаем системное имя и описание оригинальной функции
    def wrapper(*args: Any, **kwargs: Any) -> Any:  # Создаем обертку для перехвата управления при вызове
        start_time = time.perf_counter()  # Фиксируем точное время старта по процессору компьютера
        result = func(*args, **kwargs)  # Выполняем оригинальную функцию библиотеки и ждем финиша
        end_time = time.perf_counter()  # Сразу фиксируем время окончания выполнения метода
        print(f"[PERFORMANCE] {func.__name__}: {end_time - start_time:.6f} sec")  # Выводим разницу с округлением
        return result  # Возвращаем итог работы метода, чтобы не нарушать его логику
    return wrapper  # Возвращаем обертку в систему

def limit_calls(max_calls: int) -> Callable[..., Any]:  # Декоратор №3 (с параметром): ставит лимит на число запусков метода
    """Декоратор №3 (с параметрами): Ограничение количества вызовов метода."""

    def decorator(func: Callable[..., Any]) -> Callable[..., Any]:  # Средний слой: принимает саму декорируемую функцию
        calls = 0  # Локальный счетчик вызовов, создается один раз при старте

        @wraps(func)  # Традиционно сохраняем метаданные оригинальной функции для отчетов
        def wrapper(*args: Any, **kwargs: Any) -> Any:  # Внутренний слой: обертка, срабатывающая при каждом вызове
            nonlocal calls  # Позволяет менять переменную счетчика 'calls' уровнем выше
            if calls >= max_calls:  # Если лимит запусков исчерпан — блокируем выполнение
                raise RuntimeError(f"[LIMIT] Превышен лимит вызовов ({max_calls}) для метода '{func.__name__}'.")  # Ошибка
            calls += 1  # Если лимит не превышен, увеличиваем счетчик вызовов на 1
            return func(*args, **kwargs)  # Запускаем оригинальный метод и отдаем его результат
        return wrapper  # Возвращаем внутреннюю обертку в средний слой
    return decorator  # Возвращаем средний слой декоратора наружу
